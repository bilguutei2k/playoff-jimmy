"""Export the numbers the scenes may show, from the locked results, to scenes/data.js.

    python3 scenes/build_data.py

Scenes read numbers only from this file: every value of every claim in
CLAIMS.json (by its key), plus the raw series a chart needs. Refuses to run if
results.json no longer matches the hash the claims were verified against.
"""

import hashlib
import json
import subprocess
import sys
from pathlib import Path

EPISODE = Path(__file__).resolve().parent.parent
PREREGISTRATION = "2827174"   # the commit that fixed METHOD.md before any league data existed
sys.path.insert(0, str(EPISODE / "analysis"))
from verify_claims import resolve  # noqa: E402


def main():
    results_path = EPISODE / "analysis/results.json"
    digest = hashlib.sha256(results_path.read_bytes()).hexdigest()
    claims = json.loads((EPISODE / "CLAIMS.json").read_text())["claims"]
    stale = [c["id"] for c in claims if c["results_sha256"] != digest]
    if stale:
        raise SystemExit("results.json does not match the verified claims (%s); re-verify first." % ", ".join(stale))
    results = json.loads(results_path.read_text())
    values, sources = {}, {}
    for claim in claims:
        for item in claim["values"]:
            values[item["key"]] = resolve(results, item["key"])
            sources.setdefault(item["key"], []).append(claim["id"])
    peers = results["peers_primary_threshold"]
    ids = {"butler": "butleji01", "murray": "murraja01"}

    def runs(name):
        """Each eligible run: his change per 36, the peer median, and every peer's change (peer set A, 100 minutes)."""
        return [{"season": r["season"], "delta": r["delta_points_per_36"], "peer_median": r["peer_median"],
                 "peers": sorted(p["delta_points_per_36"] for p in peers[r["season"]] if p["player"] != ids[name])}
                for r in results["benchmark"][name]["per_season"]["A_100"] if r["eligible"]]

    def above(rows):
        return [{"season": r["season"], "above": r["delta_points_per_36"] > r["peer_median"]} for rows_ in [rows] for r in rows_
                if r.get("eligible", True)]

    matched = results["exploratory"]["matched_peers"]
    games = {(s["season"]): s for s in results["subjects"]["butler"] if s.get("measures")}
    band = next(v for v in results["variability"] if v["player"] == "butler" and v["season"] == "2021-22")
    series = {
        # Every eligible player-season's change in points per 36 (the population behind PJ-C001).
        "league_delta_per_36_100": sorted(p["delta_points_per_36"] for pool in peers.values() for p in pool),
        # Butler's eligible runs against their season's peers (behind PJ-C005).
        "butler_runs_A100": runs("butler"),
        # Above or below the season's peer median, by peer group (behind PJ-C005, PJ-C010, PJ-C013).
        "above_median": {name: {"all": above(results["benchmark"][name]["per_season"]["A_100"]),
                                "similar": above(matched[name]["rate_within_3"]["per_season"])} for name in ids},
        "butler_playoff_games": {s: games[s]["measures"]["playoff_games"] for s in games},
        # 2021-22 regular-season 17-game stretches (behind PJ-C007).
        "variability_butler_2021_22": {"quantiles": band["window_quantiles"], "playoff": band["playoff_points_per_36"],
                                       "n_windows": band["n_windows"]},
    }
    log = subprocess.run(["git", "-C", str(EPISODE), "log", "-1", "--format=%h %cs", PREREGISTRATION],
                         capture_output=True, text=True, check=True).stdout.split()
    meta = {"preregistration_commit": log[0], "preregistration_date": log[1]}
    payload = {"results_sha256": digest, "analysis_revision": claims[0]["analysis_revision"],
               "values": values, "value_claims": sources, "series": series, "meta": meta}
    text = "// Generated by scenes/build_data.py from analysis/results.json. Do not edit.\n"
    text += "window.SCENE_DATA = " + json.dumps(payload, indent=1, sort_keys=True, ensure_ascii=False) + ";\n"
    (EPISODE / "scenes/data.js").write_text(text)
    print("Wrote scenes/data.js: %d claim values, %d series (results %s)" % (len(values), len(series), digest[:12]))


if __name__ == "__main__":
    main()
